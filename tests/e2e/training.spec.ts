test("lost create response retries once; edit conflict preserves form until explicit reload", async ({ page }) => {
  await page.goto("/entrenamiento"); await page.getByRole("button", { name: "Nueva rutina", exact: true }).click();
  await page.getByLabel("Nombre", { exact: true }).fill("Guardado recuperable");
  await page.getByLabel("Nombre del ejercicio", { exact: true }).fill("Sentadillas");
  await page.getByLabel("Repeticiones por vuelta").fill("10");
  let loseResponse = true;
  await page.route("**/api/training/routines", async (route) => {
    if (route.request().method() === "POST" && loseResponse) { loseResponse = false; await route.fetch(); await route.abort("failed"); }
    else await route.continue();
  });
  await page.getByRole("button", { name: "Guardar rutina", exact: true }).click();
  await expect(page.locator("main").getByRole("alert")).toContainText("No pudimos confirmar el guardado");
  await expect(page.getByLabel("Nombre", { exact: true })).toHaveValue("Guardado recuperable");
  await page.getByRole("button", { name: "Reintentar guardado", exact: true }).click();
  await page.getByRole("button", { name: "Ver Guardado recuperable", exact: true }).click();
  const rows = (await pool.query("SELECT id FROM training_routines WHERE owner_member_id=$1", [memberId])).rows;
  expect(rows).toHaveLength(1);
  await page.getByRole("button", { name: "Editar rutina", exact: true }).click();
  await page.getByLabel("Nombre", { exact: true }).fill("Mi cambio local");
  await pool.query("UPDATE training_routines SET name='Cambio remoto',version=version+1 WHERE id=$1", [rows[0].id]);
  await page.getByRole("button", { name: "Guardar rutina", exact: true }).click();
  await expect(page.locator("main").getByRole("alert")).toContainText("cambió en otro dispositivo");
  await expect(page.getByLabel("Nombre", { exact: true })).toHaveValue("Mi cambio local");
  await page.getByRole("button", { name: "Recargar registro", exact: true }).click();
  await page.getByRole("button", { name: "Seguir editando", exact: true }).click();
  await expect(page.getByLabel("Nombre", { exact: true })).toHaveValue("Mi cambio local");
  await page.getByRole("button", { name: "Recargar registro", exact: true }).click();
  await page.getByRole("button", { name: "Confirmar recarga", exact: true }).click();
  await expect(page.getByLabel("Nombre", { exact: true })).toHaveValue("Cambio remoto");
  await page.getByLabel("Nombre", { exact: true }).fill("Cambio final");
  await page.getByRole("button", { name: "Guardar rutina", exact: true }).click();
  await expect(page.getByRole("button", { name: "Ver Cambio final", exact: true })).toBeVisible();
});
