import { expect, test } from "@playwright/test";
import { mkdir } from "node:fs/promises";
import { diaryDatabase, diaryServer, diaryProfile } from "../training-diary-fixture.mjs";
let db: Awaited<ReturnType<typeof diaryDatabase>>, server: Awaited<ReturnType<typeof diaryServer>>;
test.skip(!process.env.FAMILY_UTILS_TEST_DATABASE_URL, "requires explicit isolated PostgreSQL");
test.beforeAll(async () => { db = await diaryDatabase(); server = await diaryServer(db.url, true, true, true, true); });
test.afterAll(async () => { await server?.close(); await db?.close(); });
test("HIIT timer previews a preset, records a completed short session and protects operation data", async ({ page, context }, testInfo) => {
  const isMobile = ["iPhone viewport", "Android viewport", "diary-mobile", "diary-webkit"].includes(testInfo.project.name);
  const visualDir = process.env.HIIT_VISUAL_QA_DIR ?? "test-results/hiit-visual";
  await mkdir(visualDir, { recursive: true });
  await db.pool.query("SELECT public.training_diary_transition()");
  const clockStart = new Date();
  await page.clock.install({ time: clockStart });
  const profile = await diaryProfile(server, "Alex", db.pool);
  const cookies = profile.cookie.split("; ").map(item => { const [name, ...rest] = item.split("="); return { name, value: rest.join("="), url: server.origin }; });
  await context.addCookies(cookies);
  await page.goto(`${server.origin}/entrenamiento?seccion=temporizador`);
  await expect(page.getByRole("heading", { name: "Temporizador" })).toBeVisible();
  await expect(page.locator('a[href="/entrenamiento?seccion=temporizador"][aria-current="page"]')).not.toHaveCount(0);
  await page.getByRole("button", { name: /Intervalos 20\/10/ }).click();
  await expect(page.locator('[aria-label="Duración prevista 4:00"]')).toBeVisible();
  await expect(page.getByText("Incluye 0:10 de preparación. Sin descanso al terminar.")).toBeVisible();
  await expect(page.getByRole("button", { name: "Iniciar entrenamiento" })).toBeInViewport();
  if (isMobile) await page.screenshot({ path: `${visualDir}/setup-${testInfo.project.name}.png` });
  if (isMobile) {
    await page.setViewportSize({ width: 360, height: 640 });
    await expect(page.getByRole("button", { name: "Iniciar entrenamiento" })).toBeInViewport();
    await page.screenshot({ path: `${visualDir}/setup-360x640-${testInfo.project.name}.png` });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: `${visualDir}/setup-390x844-${testInfo.project.name}.png` });
  }
  await page.getByRole("button", { name: /Intervalos 40\/20/ }).click();
  await expect(page.locator('[aria-label="Duración prevista 7:50"]')).toBeVisible();
  await expect(page.getByText("Incluye 0:10 de preparación. Sin descanso al terminar.")).toBeVisible();
  await page.getByRole("button", { name: /Intervalos 20\/10/ }).click();
  await page.getByText("Personalizar tiempos").click();
  await page.getByLabel("Preparación (segundos)").fill("0");
  await page.getByLabel("Trabajo (segundos)").fill("4");
  await page.getByLabel("Descanso (segundos)").fill("0");
  await page.getByLabel("Rondas").fill("1");
  await expect(page.getByText("Sin preparación. Sin descanso al terminar.")).toBeVisible();
  const startButton = page.getByRole("button", { name: "Iniciar entrenamiento" });
  await page.getByLabel("Trabajo (segundos)").fill("0");
  await expect(startButton).toBeDisabled();
  await expect(page.locator("#hiit-config-error")).toBeVisible();
  await page.getByLabel("Preparación (segundos)").fill("-1");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Preparación (segundos)").fill("0");
  await page.getByLabel("Descanso (segundos)").fill("3601");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Descanso (segundos)").fill("0");
  await page.getByLabel("Trabajo (segundos)").fill("1.5");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Trabajo (segundos)").fill("4");
  await page.getByLabel("Trabajo (segundos)").fill("3601");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Trabajo (segundos)").fill("4");
  await page.getByLabel("Rondas").fill("0");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Rondas").fill("-1");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Rondas").fill("101");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Rondas").fill("100");
  await page.getByLabel("Trabajo (segundos)").fill("3600");
  await expect(startButton).toBeDisabled();
  await page.getByLabel("Trabajo (segundos)").fill("4");
  await page.getByLabel("Rondas").fill("1");
  await expect(startButton).toBeEnabled();
  await page.clock.pauseAt(new Date());
  await page.getByRole("button", { name: "Iniciar entrenamiento" }).click();
  await page.clock.runFor(100);
  await expect(page.locator('[data-focus-mode="true"]')).toBeVisible();
  await expect(page.getByRole("button", { name: "Pausar" })).toBeFocused();
  if (isMobile) await expect(page.getByRole("navigation", { name: "Navegación de la página" })).toBeHidden();
  else await expect(page.getByRole("navigation", { name: "Aplicaciones" })).toBeHidden();
  if (isMobile) {
    await page.setViewportSize({ width: 360, height: 640 });
    await expect(page.locator("p[class*=hiitClock]")).toBeInViewport();
    await expect(page.getByRole("button", { name: "Pausar" })).toBeInViewport();
    await page.screenshot({ path: `${visualDir}/run-360x640-${testInfo.project.name}.png` });
    await page.setViewportSize({ width: 390, height: 844 });
  }
  if (isMobile) {
    await page.setViewportSize({ width: 667, height: 375 });
    await expect.poll(() => page.locator("p[class*=hiitClock]").evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(80);
    await page.screenshot({ path: `${visualDir}/run-667x375-${testInfo.project.name}.png` });
    await page.setViewportSize({ width: 390, height: 844 });
  }
  await page.getByRole("button", { name: "Salir del modo foco" }).click();
  await expect(page.getByRole("button", { name: "Volver al modo foco" })).toBeVisible();
  if (isMobile) await expect(page.getByRole("navigation", { name: "Navegación de la página" })).toBeVisible();
  else await expect(page.getByRole("navigation", { name: "Aplicaciones" })).toBeVisible();
  await page.getByRole("button", { name: "Volver al modo foco" }).click();
  await expect(page.locator('[data-focus-mode="true"]')).toBeVisible();
  await page.getByRole("button", { name: "Pausar" }).click();
  await expect(page.getByRole("button", { name: "Reanudar" })).toBeFocused();
  await page.getByRole("button", { name: "Reanudar" }).click();
  await expect(page.getByRole("button", { name: "Pausar" })).toBeVisible();
  await page.clock.runFor(4_000);
  await expect(page.getByRole("heading", { name: "Entrenamiento completo" })).toBeVisible({ timeout: 10000 });
  await page.getByRole("button", { name: "Registrar en mi diario" }).click();
  await expect(page.getByLabel("Duración (minutos, opcional)")).toHaveValue("1");
  await expect(page.getByLabel("¿Qué hiciste?")).toHaveValue(/HIIT/);
  await page.getByRole("button", { name: "Guardar actividad" }).click();
  await expect(page.getByText("Sesión registrada en el diario.")).toBeVisible();
  await expect(page.getByRole("link", { name: "Ver en mi diario" })).toHaveAttribute("href", /detalle=/);
  const rows = await db.pool.query("SELECT count(*)::int AS n FROM training_entries WHERE owner_member_id=$1", [profile.id]);
  expect(rows.rows[0].n).toBe(1);
});
