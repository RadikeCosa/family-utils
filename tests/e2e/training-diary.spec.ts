test("family-day rollover keeps open form dates; rollback reader works in the previous presentation", async ({ page }) => {
  await page.goto(`${server.origin}/entrenamiento`);
  const today = (await diaryCall(server, profile, "entries")).body.today;
  const date = new Date(`${today}T12:00:00Z`); date.setUTCDate(date.getUTCDate() + 1); const tomorrow = date.toISOString().slice(0, 10);
  await page.getByRole("button", { name: "Registrar lo realizado", exact: true }).click();
  await page.getByLabel("¿Qué hiciste?").fill("Borrador anterior a medianoche");
  let rollover = false;
  await page.route(/\/api\/training\/(summary|entries)\?/, async route => {
    const response = await route.fetch(), body = await response.json();
    if (rollover) { body.today = tomorrow; body.serverNow = `${tomorrow}T03:00:00Z`; body.nextDayAt = `${tomorrow}T23:00:00Z`; }
    await route.fulfill({ response, json: body });
  });
  rollover = true; await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await expect(page.getByLabel("Fecha", { exact: true })).toHaveValue(today);
  await expect(page.getByLabel("¿Qué hiciste?")).toHaveValue("Borrador anterior a medianoche");
  page.once("dialog", dialog => dialog.accept()); await page.getByRole("button", { name: "Cancelar", exact: true }).click();
  await expect(page.getByLabel("Ir a una fecha", { exact: true })).toHaveValue(tomorrow);
  await page.unrouteAll({ behavior: "wait" });
  const created = await diaryCall(server, profile, "entries", "POST", { input: { date: today, kind: "rest", plan: null, result: { text: "Descanso de recuperación" }, disposition: "open", sourceRoutineId: null }, operationKey: randomUUID() }); expect(created.status).toBe(201);
  const reader = await diaryServer(db.url, false, false);
  try {
    await page.goto(`${reader.origin}/entrenamiento`);
    await expect(page.getByText(/Modo de consulta/)).toBeVisible();
    await expect(page.getByRole("button", { name: "Registrar lo realizado", exact: true })).toHaveCount(0);
    await page.getByLabel("Buscar en mi diario").fill("recuperacion");
    await expect(page.locator("article")).toHaveCount(1);
    await page.getByRole("button", { name: "Ver anotación", exact: true }).click();
    await expect(page.locator("#entry-detail-title")).toHaveText("Descanso de recuperación");
    await expect(page.getByRole("button", { name: "Archivar anotación", exact: true })).toHaveCount(0);
    expect((await new AxeBuilder({ page }).include("main").analyze()).violations).toEqual([]);
  } finally { await reader.close(); }
});
test("conflict review preserves the draft and reapplies explicitly against the latest version", async ({ page }) => {
  const today = (await diaryCall(server, profile, "entries")).body.today;
  const input = { date: today, kind: "training", plan: null, result: { text: "Registro original" }, disposition: "open", sourceRoutineId: null };
  const created = await diaryCall(server, profile, "entries", "POST", { input, operationKey: randomUUID() });
  await page.goto(`${server.origin}/entrenamiento?detalle=${created.body.item.id}`);
  await page.getByRole("button", { name: "Corregir lo realizado", exact: true }).click();
  await page.getByLabel("¿Qué hiciste?").fill("Mi borrador conservado");
  const remote = await diaryCall(server, profile, `entries/${created.body.item.id}`, "PATCH", { action: "edit", input: { ...input, result: { text: "Cambio en otro dispositivo" } }, version: 1, operationKey: randomUUID() }); expect(remote.status).toBe(200);
  await page.getByRole("button", { name: "Guardar anotación", exact: true }).click();
  await page.getByRole("button", { name: "Revisar versión guardada", exact: true }).click();
  await expect(page.getByLabel("¿Qué hiciste?")).toHaveValue("Mi borrador conservado");
  await expect(page.getByText(/Fecha: .*Versión 2/)).toBeVisible();
  await page.getByRole("button", { name: "Usar esta versión como base y conservar mi borrador", exact: true }).click();
  await page.getByRole("button", { name: "Guardar anotación", exact: true }).click();
  await expect(page.locator("#entry-detail-title")).toHaveText("Mi borrador conservado");
  expect((await diaryCall(server, profile, `entries/${created.body.item.id}`)).body.item.version).toBe(3);
  const skipped = await diaryCall(server, profile, "entries", "POST", { input: { ...input, plan: { text: "Omisión manual" }, result: null, disposition: "skipped" }, operationKey: randomUUID() });
  await page.goto(`${server.origin}/entrenamiento?detalle=${skipped.body.item.id}`);
  await page.getByRole("button", { name: "Editar plan", exact: true }).click();
  await page.getByLabel("¿Qué tenés previsto?").fill("Plan corregido sin borrar la omisión");
  await page.getByRole("button", { name: "Guardar anotación", exact: true }).click();
  await expect(page.locator("section[aria-labelledby=entry-detail-title]")).toContainText("No realizado");
});
