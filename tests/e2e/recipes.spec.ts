test("conflicting edit retains copyable draft while displaying server version", async ({ page }) => {
  const created = await api.post("/api/recipes", { data: { title: `Sopa ${randomUUID()}` } }).then(r => r.json());
  await page.goto(`/recetas/${created.idea.id}`); await page.getByRole("button", { name: "Editar receta", exact: true }).click();
  await page.getByRole("textbox", { name: "Preparación", exact: true }).fill("Mi borrador");
  expect((await api.patch(`/api/recipes/${created.idea.id}`, { data: { expectedVersion: 1, preparation: "Cambio del servidor" } })).status()).toBe(200);
  await page.getByRole("button", { name: "Guardar receta", exact: true }).click(); await expect(page.getByRole("alert").filter({ hasText: "La receta cambió" })).toContainText("La receta cambió");
  await expect(page.getByRole("textbox", { name: "Preparación", exact: true })).toHaveValue("Mi borrador");
  await page.getByRole("button", { name: "Consultar versión actual", exact: true }).click(); await expect(page.getByRole("region", { name: "Versión actual del servidor", exact: true })).toContainText("Cambio del servidor");
  await page.getByText("Texto del borrador para copiar", { exact: true }).click(); await expect(page.locator("pre").filter({ hasText: "Mi borrador" })).toBeVisible();
});

test("tags can be created with keyboard, copied in drafts and combined as AND filters", async ({ page }) => {
  await api.post("/api/recipes", { data: { title: "Ensalada fresca", tags: ["almuerzo", "deVerano"] } });
  await api.post("/api/recipes", { data: { title: "Sopa caliente", tags: ["almuerzo", "invierno"] } });
  await api.post("/api/recipes", { data: { title: "Helado", tags: ["deVerano"] } });
  await page.goto("/recetas");
  await expect(page.getByRole("list", { name: "Recetas de la familia" }).getByRole("link")).toHaveCount(3);
  const filter = page.getByRole("combobox", { name: "Filtrar por etiquetas", exact: true });
  await filter.focus(); await filter.press("ArrowUp"); await filter.press("Enter");
  await expect(page.getByRole("list", { name: "Recetas de la familia" }).getByRole("link")).toHaveCount(1);
  await page.getByRole("button", { name: "Quitar etiqueta invierno", exact: true }).click();
  await expect(page.getByRole("list", { name: "Recetas de la familia" }).getByRole("link")).toHaveCount(3);
  await filter.fill("almuerzo"); await filter.press("ArrowDown"); await filter.press("Enter");
  await expect(page).toHaveURL(/tag=almuerzo/);
  await expect(page.getByRole("list", { name: "Recetas de la familia" }).getByRole("link")).toHaveCount(2);
  await filter.fill("verano"); await filter.press("ArrowDown"); await filter.press("Enter");
  await expect(page.getByRole("list", { name: "Recetas de la familia" }).getByRole("link")).toHaveCount(1);
  await filter.fill("invierno");
  await expect(page.getByRole("option", { name: "#invierno (0)", exact: true })).toHaveAttribute("aria-disabled", "true");
  await filter.press("Escape");
  await page.getByRole("link", { name: "Ensalada fresca", exact: true }).click();
  await page.getByRole("button", { name: "Editar receta", exact: true }).click();
  const editor = page.getByRole("combobox", { name: "Etiquetas de la receta", exact: true });
  await editor.fill("rápida"); await editor.press("Enter");
  await page.getByText("Texto del borrador para copiar", { exact: true }).click();
  await expect(page.locator("pre")).toContainText("#rápida");
  await page.getByRole("button", { name: "Guardar receta", exact: true }).click();
  await expect(page.getByRole("link", { name: "#rápida", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Volver a Recetas", exact: true }).click();
  await expect(page).toHaveURL(/tag=almuerzo.*tag=deverano/);
  await expect(page.getByRole("button", { name: "Actualizar lista", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Actualizar lista", exact: true }).click();
  await page.getByRole("button", { name: "Limpiar filtros", exact: true }).click();
  await expect(page.getByRole("list", { name: "Recetas de la familia" }).getByRole("link")).toHaveCount(3);
  await page.getByLabel("Nombre del nuevo plato").fill("Receta etiquetada al crear");
  const creating = page.getByRole("combobox", { name: "Etiquetas del nuevo plato", exact: true });
  await creating.fill("para llevar"); await creating.press("Enter");
  await page.getByRole("button", { name: "Crear receta", exact: true }).click();
  await expect(page.getByRole("link", { name: "#para llevar", exact: true })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
});

test("return from detail restores loaded pages and scroll, history and catalog changes", async ({ page }) => {
  for (let n = 0; n < 25; n++) await api.post("/api/recipes", { data: { title: `Plato ${String(n).padStart(2, "0")}`, tags: ["familia"] } });
  await page.goto("/recetas?tag=familia");
  const list = page.getByRole("list", { name: "Recetas de la familia" });
  await expect(list.getByRole("link")).toHaveCount(20);
  await page.getByRole("button", { name: "Ver más recetas", exact: true }).click();
  await expect(list.getByRole("link")).toHaveCount(25);
  const last = list.getByRole("link").last();
  await last.scrollIntoViewIfNeeded(); const scroll = await page.evaluate(() => window.scrollY);
  await last.click();
  await expect(page.getByRole("button", { name: "Editar receta", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Volver a Recetas", exact: true }).click();
  await expect(list.getByRole("link")).toHaveCount(25);
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(scroll - 80);
  await page.getByRole("searchbox", { name: "Buscar recetas", exact: true }).fill("Plato 00");
  await expect(list.getByRole("link")).toHaveCount(1);
  await page.getByRole("button", { name: "Limpiar filtros", exact: true }).click();
  await expect(page).toHaveURL(/\/recetas$/);
  await page.goBack(); await expect(page).toHaveURL(/q=Plato\+00/);
  await expect(list.getByRole("link")).toHaveCount(1);
  await page.goto("/recetas?tag=familia"); await expect(list.getByRole("link")).toHaveCount(20);
  await api.post("/api/recipes", { data: { title: "Cambio concurrente", tags: ["familia"] } });
  await page.getByRole("button", { name: "Ver más recetas", exact: true }).click();
  await expect(page.getByRole("button", { name: "Actualizar lista", exact: true })).toBeVisible();
  await expect(list.getByRole("link")).toHaveCount(20);
  await page.getByRole("button", { name: "Actualizar lista", exact: true }).click();
  await expect(list.getByRole("link", { name: "Cambio concurrente", exact: true })).toBeVisible();
  await page.goto("/recetas?tag=inexistente");
  await expect(page).toHaveURL(/\/recetas$/);
  await expect(page.getByRole("status").filter({ hasText: "Se quitaron etiquetas" })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBe(0);
  await page.screenshot({ path: `test-results/recipes-list-${test.info().project.name.replaceAll(" ", "-")}.png`, fullPage: true });
});
